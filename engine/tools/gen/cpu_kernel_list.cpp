// Build-time generator: lists every kernel in the concatenated kernel source,
// including kernels instantiated through macros, and whether it uses barriers.
//   cpu_kernel_list <kernel_source.txt> <out.inc>
#include <algorithm>
#include <fstream>
#include <iostream>
#include <map>
#include <regex>
#include <sstream>
#include <string>
#include <vector>

namespace {
struct Macro {
  std::vector<std::string> params;
  std::string body;
};
std::vector<std::string> split_args(const std::string& s) {
  std::vector<std::string> out;
  std::stringstream in(s);
  std::string part;
  while (std::getline(in, part, ',')) {
    const auto a = part.find_first_not_of(" \t"), b = part.find_last_not_of(" \t");
    out.push_back(a == std::string::npos ? "" : part.substr(a, b - a + 1));
  }
  return out;
}
bool has_barrier(const std::string& s) { return s.find("BARRIER") != std::string::npos; }
}  // namespace

int main(int argc, char** argv) {
  if (argc != 3) {
    std::cerr << "usage: cpu_kernel_list source.txt out.inc\n";
    return 2;
  }
  std::ifstream in(argv[1], std::ios::binary);
  std::string text((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
  // Drop comments (keeping line breaks), then join continued lines.
  {
    std::string clean;
    for (size_t i = 0; i < text.size();) {
      if (text.compare(i, 2, "/*") == 0) {
        const size_t end = text.find("*/", i + 2);
        for (size_t k = i; k < std::min(end == std::string::npos ? text.size() : end + 2, text.size()); ++k)
          if (text[k] == '\n') clean += '\n';
        i = end == std::string::npos ? text.size() : end + 2;
      } else if (text.compare(i, 2, "//") == 0) {
        while (i < text.size() && text[i] != '\n') ++i;
      } else {
        clean += text[i++];
      }
    }
    text.swap(clean);
  }
  text = std::regex_replace(text, std::regex("\\\\\r?\n"), " ");  // join continued lines
  std::vector<std::string> lines;
  {
    std::stringstream ss(text);
    std::string line;
    while (std::getline(ss, line)) lines.push_back(line);
  }
  const std::regex define_re("^\\s*#define\\s+(\\w+)\\(([^)]*)\\)(.*)$");
  const std::regex kernel_re("KERNEL\\s+void\\s+(\\w+)\\s*\\(");
  const std::regex call_re("^\\s*(\\w+)\\(([^)]*)\\)\\s*$");
  std::map<std::string, Macro> macros;
  std::vector<std::pair<std::string, bool>> kernels;
  for (size_t i = 0; i < lines.size(); ++i) {
    std::smatch m;
    const std::string& line = lines[i];
    if (std::regex_match(line, m, define_re)) {
      if (line.find("KERNEL") != std::string::npos) macros[m[1]] = Macro{split_args(m[2]), m[3]};
      continue;
    }
    if (std::regex_match(line, m, call_re) && macros.count(m[1])) {
      const Macro& macro = macros[m[1]];
      const auto args = split_args(m[2]);
      std::string body = macro.body;
      for (size_t k = 0; k < macro.params.size() && k < args.size(); ++k)
        body = std::regex_replace(body, std::regex("\\b" + macro.params[k] + "\\b"), args[k]);
      body = std::regex_replace(body, std::regex("\\s*##\\s*"), "");
      for (std::sregex_iterator it(body.begin(), body.end(), kernel_re), end; it != end; ++it) {
        // Barrier use: from this kernel to the next kernel in the expansion.
        const size_t from = size_t(it->position());
        auto next = it;
        ++next;
        const size_t to = next == end ? body.size() : size_t(next->position());
        kernels.emplace_back((*it)[1], has_barrier(body.substr(from, to - from)));
      }
      continue;
    }
    if (std::regex_search(line, m, kernel_re)) {
      std::string span;
      for (size_t j = i; j < lines.size(); ++j) {
        if (j > i && (std::regex_search(lines[j], kernel_re) || std::regex_match(lines[j], define_re))) break;
        span += lines[j] + "\n";
      }
      kernels.emplace_back(m[1], has_barrier(span));
    }
  }
  std::ostringstream out;
  out << "// Generated by cpu_kernel_list; do not edit.\n";
  for (auto& k : kernels) out << "ADR_CPU_KERNEL(" << k.first << ", " << (k.second ? "true" : "false") << ")\n";
  std::ifstream old(argv[2], std::ios::binary);
  std::string previous((std::istreambuf_iterator<char>(old)), std::istreambuf_iterator<char>());
  if (previous != out.str()) std::ofstream(argv[2], std::ios::binary) << out.str();
  std::cerr << kernels.size() << " CPU kernels\n";
  return kernels.empty() ? 1 : 0;
}
